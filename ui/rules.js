// モーダルの開閉を、その時点でページ上に存在する全ての .btn-open-rules ボタンに結びつける。
// 動的に描画される画面(render()の中など)でボタンを再生成する場合は、
// その都度これを呼び直しても害はない(毎回同じ内容で上書きされるだけ)。
export function setupRulesModal() {
  const overlay = document.getElementById("rules-modal-overlay");
  const content = document.getElementById("rules-modal-content");
  const closeBtn = document.getElementById("btn-close-rules");
  if (!overlay || !content || !closeBtn) return;

  if (!content.dataset.filled) {
    content.innerHTML = RULES_HTML;
    content.dataset.filled = "1";
  }

  const openRules = () => {
    overlay.style.display = "flex";
    content.scrollTop = 0; // 開くたびに先頭から読めるようにする
  };
  const closeRules = () => {
    overlay.style.display = "none";
  };

  closeBtn.onclick = closeRules;
  overlay.onclick = (e) => {
    if (e.target === overlay) closeRules(); // モーダルの外側をクリックしても閉じられるようにする
  };

  for (const btn of document.querySelectorAll(".btn-open-rules")) {
    btn.onclick = openRules;
  }
}
